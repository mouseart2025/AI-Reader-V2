def main() -> None:
    src = OUT_DIR / f"story_5_5_sample_180_{STAMP}.json"
    data = json.loads(src.read_text(encoding="utf-8"))

    missing: list[str] = []
    for e in data["edges"]:
        j = JUDGMENTS.get(e["child"])
        if j is None:
            missing.append(e["child"])
            e["verdict"], e["note"] = "", ""
        else:
            e["verdict"], e["note"] = j

    # 汇总
    def cnt(v: str, stratum: str | None = None) -> int:
        return sum(
            1 for e in data["edges"]
            if e["verdict"] == v and (stratum is None or e["stratum"] == stratum)
        )

    total = len(data["edges"])
    n_bad, n_ok, n_q = cnt(_BAD), cnt(_OK), cnt(_Q)

    lines = [
        "# Story 5.5 — 三国层级边 180 条人工抽查表(已判定)",
        "",
        "- 来源:`/tmp/sanguo-rebuild`(三国 120 章,Epic 5 当前代码重建后)",
        f"- 边总数:{data['total_edges']} · 本次抽样:{total}",
        "- 抽样:核心层 17 条**全查**;常规层 81;微观层补足到 180",
        "- 口径:「child 是否确实位于 parent 之内」,按《三国演义》地理常识判",
        "- **存疑**不计入错边(名称变体 / 人名为地点 / 合成节点 / 歧义)",
        "",
        "## 汇总",
        "",
        "| 分层 | 抽样 | 正确 | 错误 | 存疑 |",
        "|------|------|------|------|------|",
    ]
    for st, label in (("core", "核心"), ("regular", "常规"), ("micro", "微观")):
        s = sum(1 for e in data["edges"] if e["stratum"] == st)
        lines.append(
            f"| {label} | {s} | {cnt(_OK, st)} | {cnt(_BAD, st)} | {cnt(_Q, st)} |"
        )
    lines += [
        f"| **合计** | **{total}** | **{n_ok}** | **{n_bad}** | **{n_q}** |",
        "",
        f"**错边率 {n_bad}/{total} = {n_bad / total:.1%}**"
        f"(验收目标 ≤2/180 = 1.1%) → "
        f"**{'PASS' if n_bad <= 2 else 'FAIL'}**",
        "",
        "## 明细",
        "",
        "| # | 分层 | child | parent | child_tier | parent_tier | 判定 | 备注 |",
        "|---|------|-------|--------|-----------|-------------|------|------|",
    ]
    for i, e in enumerate(data["edges"], 1):
        lines.append(
            f"| {i} | {e['stratum']} | {e['child']} | {e['parent']} | "
            f"{e['child_tier'] or '-'} | {e['parent_tier'] or '-'} | "
            f"{e['verdict']} | {e['note']} |"
        )

    (OUT_DIR / f"story_5_5_sample_180_{STAMP}.md").write_text(
        "\n".join(lines), encoding="utf-8")
    src.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"抽样 {total}: 正确 {n_ok} / 错误 {n_bad} / 存疑 {n_q}")
    print(f"错边率 {n_bad}/{total} = {n_bad / total:.1%} "
          f"(目标 ≤2/180) → {'PASS' if n_bad <= 2 else 'FAIL'}")
    if missing:
        print(f"未判定 {len(missing)} 条: {missing[:10]}")


if __name__ == "__main__":
    main()
